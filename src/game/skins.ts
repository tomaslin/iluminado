export function parseColorRgb(
  color: string,
  fallbackRgb: [number, number, number] = [248, 245, 240]
): [number, number, number] {
  const clean = color.trim();
  if (clean.startsWith('#')) {
    const hex = clean.slice(1);
    if (hex.length === 6) {
      return [
        parseInt(hex.slice(0, 2), 16),
        parseInt(hex.slice(2, 4), 16),
        parseInt(hex.slice(4, 6), 16),
      ];
    }
    return fallbackRgb;
  }
  const m = clean.match(/rgba?\((\d+),\s*(\d+),\s*(\d+)(?:,\s*([\d.]+))?\)/);
  if (!m) return fallbackRgb;
  const r = Number(m[1]);
  const g = Number(m[2]);
  const b = Number(m[3]);
  const a = m[4] !== undefined ? Number(m[4]) : 1;
  return [
    Math.round(r * a + fallbackRgb[0] * (1 - a)),
    Math.round(g * a + fallbackRgb[1] * (1 - a)),
    Math.round(b * a + fallbackRgb[2] * (1 - a)),
  ];
}

export function compositeColorOnHex(color: string, baseHex: string): string {
  const baseRgb = parseColorRgb(baseHex);
  const [r, g, b] = parseColorRgb(color, baseRgb);
  const toHex = (v: number) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0');
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`;
}

export function getWcagLuminance(color: string, baseHex = '#faf6ee'): number {
  const baseRgb = parseColorRgb(baseHex);
  const [r, g, b] = parseColorRgb(color, baseRgb);
  const toLinear = (v: number) => {
    const x = v / 255;
    return x <= 0.03928 ? x / 12.92 : Math.pow((x + 0.055) / 1.055, 2.4);
  };
  return 0.2126 * toLinear(r) + 0.7152 * toLinear(g) + 0.0722 * toLinear(b);
}

export function getWcagContrast(fg: string, bg: string, bgBaseHex = '#faf6ee'): number {
  const l1 = getWcagLuminance(fg, bgBaseHex);
  const l2 = getWcagLuminance(bg, bgBaseHex);
  const lighter = Math.max(l1, l2);
  const darker = Math.min(l1, l2);
  return (lighter + 0.05) / (darker + 0.05);
}

export function isSkyDarkForHero(palette: SkinConfig['palette']): boolean {
  const darkContrastTop = getWcagContrast(palette.hudInk, palette.skyTop);
  const lightContrastTop = getWcagContrast('#faf6ee', palette.skyTop);
  const darkContrastMid = getWcagContrast(palette.hudInk, palette.skyMid);
  const lightContrastMid = getWcagContrast('#faf6ee', palette.skyMid);
  // Use light ink (#faf6ee) whenever top sky favors light ink or dark ink fails 4.5:1 on skyTop
  if (darkContrastTop < 4.5 && lightContrastTop >= darkContrastTop) return true;
  if (darkContrastMid < 4.5 && lightContrastMid > darkContrastMid) return true;
  return lightContrastTop > darkContrastTop * 1.1 && lightContrastMid >= darkContrastMid * 0.85;
}

export function getHexLuminance(hex: string): number {
  const clean = hex.trim().replace('#', '');
  if (clean.length !== 6) return 0.5;
  const r = parseInt(clean.slice(0, 2), 16) / 255;
  const g = parseInt(clean.slice(2, 4), 16) / 255;
  const b = parseInt(clean.slice(4, 6), 16) / 255;
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function isHexColorDark(hex: string): boolean {
  return getHexLuminance(hex) < 0.36;
}

export function isPureBlackOrWhite(value: string): boolean {
  const clean = value.trim().toLowerCase();
  return (
    clean === '#000' ||
    clean === '#000000' ||
    clean === '#fff' ||
    clean === '#ffffff'
  );
}

export function pickRandomSkinIndex(
  pool?: number[],
  excludeIdx?: number | null,
  rng: () => number = Math.random
): number {
  const candidates =
    pool && pool.length > 0
      ? pool.filter((idx) => idx >= 0 && idx < SKINS.length)
      : SKINS.map((_, idx) => idx);
  if (candidates.length === 0) return 0;
  if (candidates.length === 1) return candidates[0];
  const filtered =
    excludeIdx !== undefined && excludeIdx !== null
      ? candidates.filter((idx) => idx !== excludeIdx)
      : candidates;
  const activePool = filtered.length > 0 ? filtered : candidates;
  const pick = Math.floor(rng() * activePool.length) % activePool.length;
  return activePool[pick];
}

export function createShuffledSkinDeck(
  totalSkins: number = SKINS.length,
  excludeFirstIdx?: number | null,
  rng: () => number = Math.random
): number[] {
  const count = Math.max(1, totalSkins);
  const deck = Array.from({ length: count }, (_, i) => i);
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1)) % (i + 1);
    const tmp = deck[i];
    deck[i] = deck[j];
    deck[j] = tmp;
  }
  if (
    deck.length > 1 &&
    excludeFirstIdx !== undefined &&
    excludeFirstIdx !== null &&
    deck[0] === excludeFirstIdx
  ) {
    const swapIdx = 1 + (Math.floor(rng() * (deck.length - 1)) % (deck.length - 1));
    const tmp = deck[0];
    deck[0] = deck[swapIdx];
    deck[swapIdx] = tmp;
  }
  return deck;
}

export function advanceShuffledSkinDeck(
  deck: number[],
  pos: number,
  endless: boolean,
  rng: () => number = Math.random
): { nextIdx: number; nextDeck: number[]; nextPos: number; completed: boolean } {
  const safeDeck =
    deck.length > 0 ? deck : createShuffledSkinDeck(SKINS.length, null, rng);
  const nextPos = pos + 1;
  if (nextPos >= safeDeck.length) {
    if (!endless) {
      return {
        nextIdx: safeDeck[safeDeck.length - 1] ?? 0,
        nextDeck: safeDeck,
        nextPos: safeDeck.length - 1,
        completed: true,
      };
    }
    const lastIdx = safeDeck[safeDeck.length - 1] ?? null;
    const freshDeck = createShuffledSkinDeck(SKINS.length, lastIdx, rng);
    return {
      nextIdx: freshDeck[0] ?? 0,
      nextDeck: freshDeck,
      nextPos: 0,
      completed: false,
    };
  }
  return {
    nextIdx: safeDeck[nextPos] ?? 0,
    nextDeck: safeDeck,
    nextPos,
    completed: false,
  };
}
